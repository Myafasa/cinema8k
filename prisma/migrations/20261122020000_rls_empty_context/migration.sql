-- A transaction-local setting may reset to an empty string on a reused connection.
-- NULLIF makes the no-context policy fail closed with zero rows instead of a UUID cast error.
DROP POLICY tenant_isolation ON memberships;
CREATE POLICY tenant_isolation ON memberships
  USING (tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::uuid)
  WITH CHECK (tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::uuid);

